-- The generated <stem>.settings.hpp: one wxl::SettingsTraits specialization per settings struct.

local M = {}

-- A C++ string literal.
local function literal(s)
  return '"' .. s:gsub("\\", "\\\\"):gsub('"', '\\"'):gsub("\n", "\\n") .. '"'
end

-- A C++ double literal: "2.0", "0.25".
local function number(n)
  if n == math.floor(n) and math.abs(n) < 2^53 then return ("%d.0"):format(n) end
  return ("%.17g"):format(n)
end

local function write_struct(w, s)
  w("")
  w("template <>")
  w(("struct wxl::SettingsTraits<::%s>"):format(s.cpp))
  w("{")
  w(("    static constexpr const char* kSection = %s;"):format(literal(s.section)))
  w("    static constexpr ::wxl::SettingInfo kInfos[] = {")
  for _, f in ipairs(s.fields) do
    w(("        {%s, %s, %s, %s, %s, %s, %s},"):format(literal(f.name), f.kind, literal(f.doc), number(f.min),
      number(f.max), number(f.step), literal(f.ui)))
  end
  w("    };")
  w("    template <class Self, class F>")
  w("    static void Each(Self& s, F&& f)")
  w("    {")
  for i, f in ipairs(s.fields) do w(("        f(kInfos[%d], s.%s);"):format(i - 1, f.name)) end
  w("    }")
  w("};")
end

-- The header's text for the structs read from `base` (the settings header's file name).
function M.render(structs, base)
  local lines = {}
  local function w(s) lines[#lines + 1] = s or "" end
  w("// Generated by the settings tool from " .. base .. ": do not edit.")
  w("")
  w("#pragma once")
  w("")
  w('#include "' .. base .. '"')
  w("#include <wxl/Settings.hpp>")
  for _, s in ipairs(structs) do write_struct(w, s) end
  return table.concat(lines, "\n") .. "\n"
end

return M
