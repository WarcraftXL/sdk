-- The headers being built: one per atlas data file, its lines grouped by namespace, then rendered.

local M = {}

-- An address as the headers spell it: 0x00401B00.
function M.hex(n) return string.format("0x%08X", n) end

-- A set of headers, keyed by the atlas data file each one comes from.
function M.new()
  return { by_rel = {} }
end

-- The header of an atlas data file ("class/CGUnit_C.lua"), created on first use.
function M.file_of(set, rel)
  local f = set.by_rel[rel]
  if not f then f = { rel = rel, scopes = {}, order = {} }; set.by_rel[rel] = f end
  return f
end

-- The namespace `path` of a header, created on first use. Its items are { at, order, text } lines
-- or { at, order, block } line lists, sorted by address when rendered.
function M.scope_of(file, path)
  local key = table.concat(path, "::")
  local s = file.scopes[key]
  if not s then s = { path = path, items = {} }; file.scopes[key] = s; file.order[#file.order + 1] = key end
  return s
end

-- Where the header of an atlas data file goes: class/X.lua -> wxl/offsets/X.hpp, free/L.lua ->
-- wxl/offsets/free/L.hpp, <kind>/Y.lua -> wxl/offsets/<kind>/Y.hpp.
local function header_path(rel)
  local kind, base = rel:match("^(%w+)/(.+)%.lua$")
  if kind == "class" then return "include/wxl/offsets/" .. base .. ".hpp" end
  if kind == "free" then return "include/wxl/offsets/free/" .. base .. ".hpp" end
  return "include/wxl/offsets/" .. kind .. "/" .. base .. ".hpp"
end

local function by_address(a, b)
  if a.at ~= b.at then return a.at < b.at end
  if a.order ~= b.order then return a.order < b.order end
  if (a.src or 0) ~= (b.src or 0) then return (a.src or 0) < (b.src or 0) end
  return (a.text or "") < (b.text or "")
end

-- The atlas data files of one header, their sources joined: "data/class/A.lua and data/class/a.lua".
local function sources(rels)
  local names = {}
  for i, rel in ipairs(rels) do names[i] = "data/" .. rel end
  return table.concat(names, " and ")
end

-- A header's text: its namespaces sorted by name, each one's items by address.
local function render(file)
  local out = {
    "// SPDX-License-Identifier: GPL-3.0-or-later",
    "// Generated by tools/offsets/gen.lua from atlas " .. sources(file.rels or { file.rel }) .. ": do not edit.",
    "#pragma once",
    "",
    "#include <cstddef>",
    "#include <cstdint>",
  }
  table.sort(file.order)
  for _, key in ipairs(file.order) do
    local s = file.scopes[key]
    table.sort(s.items, by_address)
    out[#out + 1] = ""
    out[#out + 1] = "namespace wxl::offsets" .. (key ~= "" and ("::" .. key) or "")
    out[#out + 1] = "{"
    for _, item in ipairs(s.items) do
      if item.block then
        for _, l in ipairs(item.block) do out[#out + 1] = "    " .. l end
      else
        out[#out + 1] = "    " .. item.text
      end
    end
    out[#out + 1] = "}"
  end
  return table.concat(out, "\n") .. "\n"
end

-- One header holding several atlas data files, in the order given: their namespaces merged, each
-- item tagged with its file's rank so equal items still sort the same way.
local function merge(files)
  local rels, merged = {}, { scopes = {}, order = {} }
  for i, f in ipairs(files) do
    rels[i] = f.rel
    for _, key in ipairs(f.order) do
      local s = M.scope_of(merged, f.scopes[key].path)
      for _, item in ipairs(f.scopes[key].items) do
        local copy = {}
        for k, v in pairs(item) do copy[k] = v end
        copy.src = i
        s.items[#s.items + 1] = copy
      end
    end
  end
  merged.rels = rels
  return merged
end

-- Renders every header of the set into out_files (path -> text). Atlas data files whose headers
-- differ only in case (class/ComSat.lua, class/Comsat.lua) share one header, named after the first
-- in byte order: a case-insensitive file system (Windows, macOS) cannot hold both.
function M.render_all(set, out_files)
  local groups, keys = {}, {}
  for rel in pairs(set.by_rel) do
    local key = header_path(rel):lower()
    if not groups[key] then groups[key] = {}; keys[#keys + 1] = key end
    local g = groups[key]
    g[#g + 1] = rel
  end
  for _, key in ipairs(keys) do
    local rels = groups[key]
    table.sort(rels)
    if #rels == 1 then
      out_files[header_path(rels[1])] = render(set.by_rel[rels[1]])
    else
      local files = {}
      for i, rel in ipairs(rels) do files[i] = set.by_rel[rel] end
      out_files[header_path(rels[1])] = render(merge(files))
    end
  end
end

return M
